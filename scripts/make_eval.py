"""
Make an evaluation set from the indexed papers (for scripts/eval.py).

    python scripts/make_eval.py data/arxiv 100

For N randomly chosen papers, Nemotron writes one question that the abstract
answers. The paper itself is the ground truth. These are synthetic questions,
so say so when you report the numbers. Output: data/eval_arxiv.json
Costs N short model calls.
"""

import json
import os
import random
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from backend.nebius_client import clean_answer, get_client  # noqa: E402

PROMPT = (
    "Write ONE specific question that a researcher could answer using only the abstract below. "
    "Do not copy the title or use the paper's name. Do not mention 'the paper' or 'the abstract'. "
    "Return only the question.\n\nTitle: {t}\n\nAbstract: {a}"
)


def pick_question(text: str) -> str:
    """Return the last line of the reply that looks like a question, or ''."""
    lines = [l.strip().strip('"').strip() for l in (text or "").splitlines() if "?" in l]
    for l in reversed(lines):
        l = l.lstrip("-*0123456789. ").strip()
        if l.endswith("?") and 20 < len(l) < 300:
            return l
    return ""


def main(folder: str, n: int) -> None:
    files = sorted(f for f in os.listdir(folder) if f.endswith(".md"))
    random.Random(7).shuffle(files)
    client = get_client()
    model = os.environ.get("CHAT_MODEL", "nvidia/NVIDIA-Nemotron-3-Nano-30B-A3B")
    out = []
    failures = 0
    for name in files:
        if len(out) >= n:
            break
        text = open(os.path.join(folder, name), encoding="utf-8").read()
        title, _, abstract = text.partition("\n\n")
        r = client.chat.completions.create(
            model=model, temperature=0.3, max_tokens=1500,
            messages=[{"role": "user", "content": PROMPT.format(t=title.lstrip("# "), a=abstract.strip())}],
        )
        raw = r.choices[0].message.content
        q = pick_question(clean_answer(raw))
        if q:
            failures = 0
            out.append({"q": q, "source": name, "answerable": True})
            print(f"{len(out)}/{n}  {q}", flush=True)
        else:
            failures += 1
            if failures >= 3:   # stop early instead of paying for calls that keep failing
                sys.exit(f"Stopping: 3 replies in a row had no usable question.\n"
                         f"finish_reason={r.choices[0].finish_reason!r}\nreply={raw!r}")
    if not out:
        sys.exit("No questions were made, so nothing was saved.")
    path = os.path.join(os.path.dirname(__file__), "..", "data", "eval_arxiv.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump({"note": "Synthetic questions generated by Nemotron from each paper's abstract.", "questions": out}, f, indent=1)
    print(f"Saved {len(out)} questions to {os.path.abspath(path)}")


if __name__ == "__main__":
    main(sys.argv[1], int(sys.argv[2]) if len(sys.argv) > 2 else 100)
